const searchInput = document.getElementById('gallery-search');
const sortSelect = document.getElementById('gallery-sort');
const gallery = document.querySelector(`.gallery`);

function renderGallery() {
  const searchTerm = searchInput.value.toLowerCase().trim();
  const sortValue = sortSelect.value;

  let filteredPhotos = photos.filter(photo => {
    return searchTerm == '' || photo.tags.toLowerCase().includes(searchTerm);
  });

  filteredPhotos.sort((a, b) => {
    if (sortValue == 'date-desc') {
      return new Date(b.date) - new Date(a.date);
    } else if (sortValue == 'date-asc') {
      return new Date(a.date) - new Date(b.date);
    } else if (sortValue == 'tag-asc') {
      return a.tags.localeCompare(b.tags);
    }
  });

  gallery.innerHTML = '';

  filteredPhotos.forEach(photo => {
    const item = document.createElement('div');
    item.className = "gallery-item";
    item.innerHTML = `
      <a href="${photo.src}" target="_blank">
        <img src="${photo.src}" alt="" class="gallery-picture" decoding="async" loading="lazy">
      </a>
      <div class="gallery-description">${photo.description}</div>
      <div class="gallery-tags">Tags: ${photo.tags}</div>
    `;

    gallery.appendChild(item);
  });
}

searchInput.addEventListener('input', renderGallery);
sortSelect.addEventListener('change', renderGallery);

renderGallery();
